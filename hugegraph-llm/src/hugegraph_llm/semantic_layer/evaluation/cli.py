"""Command line entry point for the evaluation harness.

The point of this script is that the numbers in the plan document can be
regenerated by anyone, at any time, instead of being asserted. Run it in CI
to catch a retrieval regression the way a test would::

    python -m hugegraph_llm.semantic_layer.evaluation.cli \\
        --dataset .../resources/acme_eval.jsonl \\
        --url http://127.0.0.1:8081 --graph semantic_m2b \\
        --output report.json

Add ``--fail-under recall@5=0.90`` to turn a metric into a gate.
"""

import argparse
import sys
from typing import Dict, List, Optional

from pyhugegraph.client import PyHugeClient

from hugegraph_llm.semantic_layer.evaluation.runner import (
    evaluate,
    write_report,
)
from hugegraph_llm.semantic_layer.readers import GremlinSemanticReader
from hugegraph_llm.semantic_layer.retrieval import RetrievalConfig

#: Metrics that can be used as CI gates.
GATEABLE = (
    "recall@5",
    "all_gold_found_rate",
    "retrieved_joinable_rate",
    "token_saving",
    "success_rate",
)


def _parse_thresholds(raw: Optional[List[str]]) -> Dict[str, float]:
    thresholds: Dict[str, float] = {}
    for item in raw or []:
        if "=" not in item:
            raise ValueError(f"threshold must be name=value, got: {item}")
        name, value = item.split("=", 1)
        if name not in GATEABLE:
            raise ValueError(
                f"unknown metric '{name}'; gateable: {', '.join(GATEABLE)}"
            )
        thresholds[name] = float(value)
    return thresholds


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Evaluate semantic layer retrieval.",
    )
    parser.add_argument("--dataset", required=True, help="Path to .json/.jsonl dataset")
    parser.add_argument("--url", default="http://127.0.0.1:8081", help="HugeGraph URL")
    parser.add_argument("--graph", required=True, help="Graph name")
    parser.add_argument("--user", default="", help="HugeGraph user")
    parser.add_argument("--pwd", default="", help="HugeGraph password")
    parser.add_argument("--output", help="Write the JSON report here")
    parser.add_argument("--max-tokens", type=int, default=4000)
    parser.add_argument("--top-k", type=int, default=8)
    parser.add_argument("--hops", type=int, default=2)
    parser.add_argument("--max-tables", type=int, default=12)
    parser.add_argument(
        "--min-score-ratio",
        type=float,
        default=0.0,
        help="Drop expanded tables scoring below this fraction of the "
             "strongest seed (0 keeps every neighbour).",
    )
    parser.add_argument(
        "--fail-under",
        action="append",
        metavar="METRIC=VALUE",
        help=f"Exit non-zero if a metric falls below the threshold. "
             f"Gateable: {', '.join(GATEABLE)}",
    )
    parser.add_argument("--quiet", action="store_true", help="Print JSON only")
    args = parser.parse_args(argv)

    try:
        thresholds = _parse_thresholds(args.fail_under)
    except ValueError as exc:
        parser.error(str(exc))
        return 2

    client = PyHugeClient(args.url, args.graph, args.user, args.pwd)
    reader = GremlinSemanticReader(client)
    config = RetrievalConfig(
        top_k=args.top_k,
        hops=args.hops,
        max_tables=args.max_tables,
        min_score_ratio=args.min_score_ratio,
    )

    report = evaluate(
        reader,
        args.dataset,
        graph_name=args.graph,
        config=config,
        max_tokens=args.max_tokens,
    )

    if not args.quiet:
        print(report.render())
    else:
        print(report.to_json())

    if args.output:
        write_report(report, args.output)
        if not args.quiet:
            print(f"\nreport written to {args.output}")

    if thresholds:
        actual = report.overall.to_dict()
        failures = [
            f"{name}: {actual[name]:.3f} < {limit}"
            for name, limit in thresholds.items()
            if actual[name] < limit
        ]
        if failures:
            print("\nFAILED thresholds:", file=sys.stderr)
            for failure in failures:
                print(f"  {failure}", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
