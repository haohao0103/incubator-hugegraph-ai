"""Evaluation harness for the semantic layer (milestone M4).

Why this exists: neocarta's ``eval/`` is a skeleton whose own README says it
is incomplete and must not be used as a reference, so the "20-30% fewer
tokens / +10pp JOIN accuracy" figures floating around the semantic-layer
literature have no reproducible basis. This harness is what turns the
claims made in ``docs/plans/2026-09-07-graph-native-semantic-layer.md``
into numbers that can be regenerated by anyone, in CI.

**Scope, stated plainly.** This evaluates *retrieval*: given a question,
does the semantic layer hand the model the right tables, at what token
cost, in a form that can actually be joined. It does **not** evaluate
end-to-end SQL generation -- that needs a warehouse to execute against, and
without one, "execution accuracy" would have to be faked. Rather than
report a number that cannot be reproduced, the harness leaves it out and
reports what it can measure honestly.

Four metrics:

1. ``table_recall``    -- P@k / R@k of gold tables among the retrieved ones.
2. ``token_cost``      -- tokens spent, against a full-schema baseline.
3. ``join_soundness``  -- is the retrieved set mutually joinable, and are
   the gold tables reachable through declared foreign keys?
4. ``term_recall``     -- did business-term recall fire, and did it help?
"""

